import { test, expect } from '@playwright/test';

const engine = process.env.LUCID_ENGINE_URL;
test('production /studio/ integrates with the local CPU fake engine', async ({ page, request }, testInfo) => {
  test.skip(!engine, 'Set LUCID_ENGINE_URL to a local CPU fake engine');
  const stats = await (await request.get(`${engine}/stats`)).json();
  expect(stats.backend, 'This mutating test is only for a CPU fake engine').toBe('fake');
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(`${engine}/studio/`);
  await page.getByRole('button', { name: 'Enter the studio' }).click();
  await expect(page.locator('.experience')).toHaveClass(/editor-visible/);
  await expect(page.locator('.prompt-provenance')).toContainText('connected');
  await page.getByRole('button', { name: 'Reset scene', exact: true }).click();
  const input = page.locator('#editor-thought');
  await input.fill('make it winter');
  await expect(page.getByRole('button', { name: 'Remove winter', exact: true })).toBeVisible();
  await expect(page.locator('.server-words mark')).toHaveText('winter');
  await expect(page.locator('.editor-latency')).toHaveText(/\d+ ms/);
  await input.fill('also add a river');
  await expect(page.getByRole('button', { name: 'Remove river', exact: true })).toBeVisible();
  await testInfo.attach('CPU fake engine editor', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' });
  await page.getByRole('button', { name: 'Remove river', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove river', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '↶ Undo', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove river', exact: true })).toBeVisible();
  await input.focus();
  await page.keyboard.press('Alt+r');
  await expect(page.getByRole('button', { name: 'Remove winter', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Remove river', exact: true })).toHaveCount(0);
  await input.fill('please sing a song');
  await expect(page.locator('.server-words')).toHaveAttribute('data-unmatched', 'true');
  await expect(page.locator('.engine-awaiting')).toHaveCount(0);
  expect(errors).toEqual([]);
});
